"""
In-place schema migrations for AuraCRM.

Idempotent and non-destructive: safe to re-run, and it never drops a row. Use
this instead of `seed.py` when the database holds real data, since seeding
drops every table.

Run: python migrate.py
"""
from sqlalchemy import text

from database import engine, SessionLocal
from analytics import resolve_department_id


def _column_exists(conn, table: str, column: str) -> bool:
    return conn.execute(text("""
        SELECT 1 FROM information_schema.columns
        WHERE table_name = :t AND column_name = :c
    """), {"t": table, "c": column}).scalar() is not None


def drop_static_department_metrics(conn) -> None:
    """Remove the hand-entered columns now derived in analytics.py."""
    for column in ("leads_generated", "roi"):
        if _column_exists(conn, "departments", column):
            conn.execute(text(f"ALTER TABLE departments DROP COLUMN {column}"))
            print(f"  dropped departments.{column}")


def add_acquisition_department_fk(conn) -> None:
    """Add the attribution foreign key on customers."""
    if _column_exists(conn, "customers", "acquisition_department_id"):
        print("  customers.acquisition_department_id already present")
        return
    conn.execute(text("""
        ALTER TABLE customers
        ADD COLUMN acquisition_department_id INTEGER REFERENCES departments(id)
    """))
    print("  added customers.acquisition_department_id")


def backfill_acquisition_department(conn) -> None:
    """Populate the new FK from the two existing attribution signals.

    Pass 1 uses the free-text channel label via the shared alias table; pass 2
    overwrites it with the lead's source department wherever a customer was
    converted from a lead, since that link is first-party and authoritative.
    """
    dept_ids_by_name = {
        name: did for name, did in conn.execute(text("SELECT name, id FROM departments"))
    }

    updated = 0
    rows = conn.execute(text("""
        SELECT id, acquisition_channel FROM customers
        WHERE acquisition_department_id IS NULL
    """)).fetchall()
    for cust_id, channel in rows:
        dept_id = resolve_department_id(channel, dept_ids_by_name)
        if dept_id:
            conn.execute(
                text("UPDATE customers SET acquisition_department_id = :d WHERE id = :i"),
                {"d": dept_id, "i": cust_id},
            )
            updated += 1
    print(f"  backfilled {updated} customer(s) from channel labels")

    first_party = conn.execute(text("""
        UPDATE customers c
        SET acquisition_department_id = l.source_department_id
        FROM leads l
        WHERE l.converted_customer_id = c.id
          AND l.source_department_id IS NOT NULL
          AND c.acquisition_department_id IS DISTINCT FROM l.source_department_id
    """)).rowcount
    print(f"  corrected {first_party} customer(s) from first-party lead source")


def remove_autogenerated_lead_campaigns(conn) -> None:
    """Delete the per-won-lead placeholder campaigns.

    Converting a lead used to mint a zero-budget campaign named
    "Lead Source: <source> - <code>". They carry no marketing meaning and would
    swamp campaign reporting with single-customer rows.
    """
    ids = [r[0] for r in conn.execute(text(
        "SELECT id FROM campaigns WHERE name LIKE 'Lead Source: %'"
    ))]
    if not ids:
        print("  no autogenerated campaigns found")
        return
    conn.execute(
        text("DELETE FROM customer_campaigns WHERE campaign_id = ANY(:ids)"), {"ids": ids}
    )
    conn.execute(text("DELETE FROM campaigns WHERE id = ANY(:ids)"), {"ids": ids})
    print(f"  removed {len(ids)} autogenerated lead campaign(s)")


def add_campaign_dates(conn) -> None:
    """Ensure campaigns have a start date so they can be reported over time."""
    if not _column_exists(conn, "campaigns", "start_date"):
        return
    filled = conn.execute(text("""
        UPDATE campaigns SET start_date = created_at::date
        WHERE start_date IS NULL AND created_at IS NOT NULL
    """)).rowcount
    if filled:
        print(f"  set start_date on {filled} campaign(s)")


def main() -> None:
    print("Running AuraCRM migrations...")
    with engine.begin() as conn:
        drop_static_department_metrics(conn)
        add_acquisition_department_fk(conn)
        backfill_acquisition_department(conn)
        remove_autogenerated_lead_campaigns(conn)
        add_campaign_dates(conn)
    print("Done.")


if __name__ == "__main__":
    main()
